export function readCoachRequest(locale:string,text:string) {
  if (!Object.prototype.hasOwnProperty.call(coachRequestMessages,locale)) return undefined;
  const rows=coachRequestMessages[locale as CoachLocale];
  const normalize=(s:string)=>s.normalize('NFC').toLocaleLowerCase().trim().replace(/[.!?。！？]+$/u,'').trim();
  const index=rows.findIndex(row=>normalize(row[0])===normalize(text));
  if(index<0)return undefined;
  return Object.freeze({taskKind:(['meal_image_assessment','exercise_form_observation','physique_posture_observation'] as const)[index],meaning:rows[index][1],response:rows[index][2]});
}
