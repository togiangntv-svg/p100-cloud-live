export type TranslationKey = keyof typeof messages.vi | IdentityTranslationKey | PrivacyTranslationKey | ReleaseSystemTranslationKey;

export function translate(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
  const localizedM2 = m2Messages[locale as keyof typeof m2Messages];
  const m2Value = localizedM2?.[key as keyof typeof m2Messages.vi];
  const openingValue = openingMessages[locale]?.[key as OpeningTranslationKey];
  const identityLocale = isReleaseLocale(locale) ? locale : 'en';
  const identityValue = identityMessages[identityLocale]?.[key as IdentityTranslationKey];
  const privacyValue = privacyMessages[identityLocale]?.[key as PrivacyTranslationKey];
  const releaseSystemValue = releaseSystemMessages[identityLocale]?.[key as ReleaseSystemTranslationKey];
  const baseMessages = locale === 'vi' ? messages.vi : messages.en;
  const baseValue = (baseMessages as Partial<Record<TranslationKey, string>>)[key];
  return (m2Value ?? openingValue ?? identityValue ?? privacyValue ?? releaseSystemValue ?? baseValue ?? String(key)).replace(/\{(\w+)\}/gu, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function detectDeviceLocale(): Locale | null {
  let value = '';
  try {
    value = Intl.DateTimeFormat().resolvedOptions().locale || '';
  } catch {
    value = '';
  }
  if (!value && typeof globalThis.navigator !== 'undefined') value = globalThis.navigator.language || '';
  return detectLocaleFromTag(value);
}

export function localeCode(locale: Locale): string {
  return getLocaleOption(locale).code;
}

export function outcomeMessage(locale: Locale, note: string): string {
  if (note.includes('một phần') || note.includes('part')) return translate(locale, 'learnedPartly');
  if (note.includes('chưa phù hợp') || note.includes('not right')) return translate(locale, 'learnedNo');
  return translate(locale, 'learnedYes');
}
