export function isSupportedLocale(value: string | null): value is Locale {
  return LOCALE_OPTIONS.some((option) => option.id === value);
}

export function getLocaleOption(locale: Locale): LocaleOption {
  return LOCALE_OPTIONS.find((option) => option.id === locale) ?? LOCALE_OPTIONS[1];
}

export function detectLocaleFromTag(value: string): Locale | null {
  const parts = value.replace(/_/gu, '-').split('-').filter(Boolean);
  const normalized = parts[0]?.toLowerCase();
  if (normalized === 'zh') {
    const script = parts.slice(1).find((part) => part.length === 4)?.toLowerCase();
    const region = parts.slice(1).find((part) => part.length === 2 || /^\d{3}$/u.test(part))?.toUpperCase();
    if (script === 'hant' || (!script && ['HK', 'MO', 'TW'].includes(region ?? ''))) return null;
    return 'zh-Hans';
  }
  const languageMap: Record<string, Locale> = {
    vi: 'vi',
    en: 'en',
    ja: 'ja',
    ko: 'ko',
    es: 'es',
    pt: 'pt',
    ru: 'ru',
    th: 'th',
    id: 'id',
    hi: 'hi',
    bn: 'bn',
    ur: 'ur',
    ar: 'ar',
    fr: 'fr',
    de: 'de',
    tr: 'tr',
    it: 'it',
    fil: 'fil',
    tl: 'fil',
    fa: 'fa',
  };
  return normalized ? languageMap[normalized] ?? null : null;
}
